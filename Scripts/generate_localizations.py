#!/usr/bin/env python3
"""Compile the reviewed translation catalog into standard Apple resources."""
from pathlib import Path
import json, plistlib, sys
ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / 'Localization/Strings.json'
LANGUAGES = ('en', 'zh-Hans', 'zh-Hant')

def quoted(value):
    return json.dumps(value, ensure_ascii=False)

def emit(path, content):
    data = content.encode('utf-8') if isinstance(content, str) else content
    if '--check' in sys.argv:
        if not path.exists() or path.read_bytes() != data:
            raise SystemExit(f'Stale resource: {path.relative_to(ROOT)}. Run Scripts/generate_localizations.py.')
    else:
        path.write_bytes(data)

def generate():
    catalog = json.loads(CATALOG.read_text())
    for language in LANGUAGES:
        directory = ROOT / 'Sources/iMusicKit/Resources' / (language + '.lproj')
        directory.mkdir(parents=True, exist_ok=True)
        strings, plurals = [], {}
        for key, entry in sorted(catalog.items()):
            value = entry[language]
            strings.append(f'{quoted(key)} = {quoted(value)};')
            if language == 'en' and 'plural' in entry:
                plurals[key] = {
                    'NSStringLocalizedFormatKey': '%1$#@count@',
                    'count': {
                        'NSStringFormatSpecTypeKey': 'NSStringPluralRuleType',
                        'NSStringFormatValueTypeKey': 'ld',
                        **entry['plural'],
                    },
                }
        emit(directory / 'Localizable.strings', '// Generated by Scripts/generate_localizations.py\n' + '\n'.join(strings) + '\n')
        if plurals:
            emit(directory / 'Localizable.stringsdict', plistlib.dumps(plurals, sort_keys=True))
    descriptions = {
        'en': 'Receive music uploads from a computer on your local network when you open Wi-Fi Transfer.',
        'zh-Hans': '在您开启 Wi-Fi 传歌时，接收同一局域网电脑上传的音乐。',
        'zh-Hant': '在您開啟 Wi-Fi 傳歌時，接收同一區域網路電腦上傳的音樂。',
    }
    for language, description in descriptions.items():
        directory = ROOT / 'Apps/Resources' / (language + '.lproj')
        directory.mkdir(parents=True, exist_ok=True)
        emit(directory / 'InfoPlist.strings', '"NSLocalNetworkUsageDescription" = ' + quoted(description) + ';\n"Audio File" = ' + quoted({'en': 'Audio File', 'zh-Hans': '音频文件', 'zh-Hant': '音訊檔案'}[language]) + ';\n')
    print(f'Generated {len(catalog)} keys for {len(LANGUAGES)} languages.')

if __name__ == '__main__':
    generate()
